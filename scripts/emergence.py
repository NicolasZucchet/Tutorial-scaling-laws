"""Emergence: a smooth loss made of per-band accuracy steps.

The (N, D) scan measures one number, the excess loss averaged over the whole Zipf tail,
and it is a clean power law in both N and D.  This script re-measures the *same* runs
with a threshold metric on a narrow slice of contexts -- uniform top-1 accuracy on
context indices 1-1k, 2-3k, 5-6k, 10-11k and 20-30k -- and gets sigmoids that switch on
one after another as the model grows or as training proceeds.

    PYTHONPATH=src uv run python scripts/emergence.py --run        # ~70 min
    PYTHONPATH=src uv run python scripts/emergence.py --run --hs 32 64 --steps 6400
    PYTHONPATH=src uv run python scripts/emergence.py --report     # midpoints + table
    PYTHONPATH=src uv run python scripts/emergence.py --figures    # figures/emergence.png
    PYTHONPATH=src uv run python scripts/emergence.py --slide      # chart block to stdout
    PYTHONPATH=src uv run python scripts/emergence.py --write-slide

The chart block always goes to results/emergence_chart.md (and, with --slide, to stdout).
--write-slide additionally writes

    figures/emergence-chart.md    the deck's figure: legend, chart and styling script

which is what the `<!-- figure: emergence-chart -->` placeholder on "Digression: emergent
behavior under the hood" pulls in when scripts/build_slides.py expands it.  Nothing about
the plot lives in slides.md, so this script owns the figure outright.

Runs are billed to their own ledger (results/emergence_ledger.jsonl, no budget) and
checkpointed to results/emergence.json after every h, so the sweep is resumable.
"""

